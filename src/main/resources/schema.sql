-- ============================================================================
-- eCall Crash Detection & Insurance FNOL Orchestrator Schema
-- Target Engine: PostgreSQL 15+ (Compatible with H2 MODE=PostgreSQL)
-- ============================================================================

CREATE TABLE IF NOT EXISTS ecall_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL,
    vin VARCHAR(17) NOT NULL,
    crash_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    impact_delta_v DOUBLE PRECISION NOT NULL,
    airbag_deployed BOOLEAN NOT NULL,
    rollover_detected BOOLEAN NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    heading_degrees INTEGER NOT NULL,
    passengers_count INTEGER NOT NULL,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(32) NOT NULL,
    policy_number VARCHAR(40),
    claim_reference VARCHAR(40),
    dispatch_reference VARCHAR(40),
    failure_reason VARCHAR(500),
    retry_count INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ecall_incidents_event_id UNIQUE (event_id)
);

-- Composite index for querying vehicle crash history by VIN in chronological order
CREATE INDEX IF NOT EXISTS idx_incidents_vin_crash_time
    ON ecall_incidents (vin, crash_timestamp DESC);

-- Index for operational dashboard filtering by incident status and severity
CREATE INDEX IF NOT EXISTS idx_incidents_status_severity
    ON ecall_incidents (status, severity);

CREATE TABLE IF NOT EXISTS outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload VARCHAR(4000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    retry_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP WITH TIME ZONE
);

-- Composite index optimized for Outbox poller query:
-- Avoids full table scan when millions of PROCESSED rows accumulate
CREATE INDEX IF NOT EXISTS idx_outbox_status_next_attempt
    ON outbox_events (status, next_attempt_at, created_at);

CREATE INDEX IF NOT EXISTS idx_outbox_aggregate_id
    ON outbox_events (aggregate_id);
